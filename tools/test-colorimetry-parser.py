platform_headers=headers

def encode(value):
 b=bytearray()
 def tag(t,n):
  while len(b)%4:b.append(0)
  b.extend(struct.pack('<I',t<<24|n))
 def write(v):
  if isinstance(v,dict):
   tag(1,len(v))
   for k,x in v.items():write(k);write(x)
  elif isinstance(v,list):
   tag(2,len(v))
   for x in v:write(x)
  elif isinstance(v,bool):tag(11,int(v))
  elif isinstance(v,int):tag(4,0);b.extend(struct.pack('<q',v))
  elif isinstance(v,str):tag(9,len(v.encode()));b.extend(v.encode())
  else:raise TypeError(v)
 b.extend(struct.pack('<I',0xd3));write(value);return bytes(b)

def color(i,c,d=8,score=100):return {'IsVirtual':False,'ID':i,'Colorimetry':c,'Depth':d,'DynamicRange':0,'EOTF':0,'PixelEncoding':0,'Score':score}
def timing(colors):
 return {'IsVirtual':False,'ID':1,'Score':100,'HorizontalAttributes':{'Active':1920,'Total':2200,'FrontPorch':88,'SyncWidth':44,'PreciseSyncRate':0},'VerticalAttributes':{'Active':1080,'Total':1125,'FrontPorch':4,'SyncWidth':5,'PreciseSyncRate':60<<16},'ColorModes':colors}
cases=[]
def add(name,colors,want,baseline=None,internal=False,external=False,pref=10):
 cases.append({'name':name,'blob':encode(timing(colors)),'want':want,'baseline':want if baseline is None else baseline,'internal':internal,'external':external,'pref':pref,'error':False})
for field in ['depth7','missing_depth','missing_range']:
 for after in [False,True]:
  bad=color(99,10,score=500000)
  if field=='depth7':bad['Depth']=7
  if field=='missing_depth':del bad['Depth']
  if field=='missing_range':del bad['DynamicRange']
  good=color(69,16,10,440999)
  add(field+('_after' if after else '_before'),[good,bad] if after else [bad,good],69)
add('wide_gamut_fallback',[color(71,1),color(68,9,10,447999),color(99,10,7,500000)],71,baseline=68)
valid=[color(68,9,10,447999),color(69,16,10,440999),color(70,10,8,100)]
add('valid_preference',valid,70,baseline=68)
add('preference_disabled',valid,68,pref=-1)
add('internal_keeps_score',valid,68,internal=True)
add('h17p_existing_rank',valid,70,external=True)
add('same_tier_score',[color(70,10,8,100),color(72,10,10,200)],72)
add('no_valid_color',[color(99,10,7)],0)
cases[-1]['error']=True
add('bad_header',valid,0);cases[-1]['blob']=b'\x00'+cases[-1]['blob'][1:];cases[-1]['error']=True
add('truncated_record',valid,0);cases[-1]['blob']=cases[-1]['blob'][:-3];cases[-1]['error']=True
results=[]
for name,s,source_header in [('reference',ref,h),('upstream',up,h),('fixed',fixed,h)]+extra:
 variant_headers=platform_headers
 for decl in ['struct dcp_parse_ctx','enum dcp_color_eotf','enum dcp_color_format','enum dcp_colorimetry','enum dcp_color_range','struct dcp_color_mode','struct dcp_display_mode','struct dimension']:
  variant_headers+=unit(source_header,decl+' {')+';\n'
 start=s.index('#define DCP_PARSE_HEADER');end=s.index('static int parse_mode');end=s.index(unit(s,'static int parse_mode'),end)+len(unit(s,'static int parse_mode'))
 prefix=s[start:end]
 text=variant_headers+prefix+'\nint main(void){int total=0,failed=0;\n'
 for i,c in enumerate(cases):
  data=','.join(str(x) for x in c['blob']);want=c['baseline'] if name=='reference' else c['want']
  text+='{ _Alignas(8) static const unsigned char data[]={'+data+'}; struct dcp_parse_ctx ctx;struct dcp_display_mode out={0};s64 score=-1;\n'
  if name!='reference':text+=f'external_colorimetry={c["pref"]};\n'
  text+='int ret=parse(data,sizeof(data),&ctx); if(!ret) ret=parse_mode(&ctx,&out,&score,300,170,0,'+str(int(c['internal']))+','+str(int(c['external']))+');\n'
  text+='bool pass='+('(ret<0)' if c['error'] else f'(!ret && out.color_mode_id=={want} && out.mode.clock==148500 && ctx.pos==sizeof(data))')+'; total++;failed+=!pass;\n'
  text+=f'printf("{c["name"]} ret=%d id=%u clock=%d pass=%d\\n",ret,out.color_mode_id,out.mode.clock,pass);}}\n'
 text+='printf("TOTAL=%d FAILED=%d\\n",total,failed);return failed?1:0;}\n'
 p=r/('serialized-'+name+'.c');p.write_text(text)
 build=subprocess.run([os.environ.get('CC','cc'),'-Wall','-Wextra','-Wno-unused-function','-Wno-unused-variable','-Wno-sign-compare','-fsanitize=address,undefined','-g',str(p),'-o',str(p.with_suffix(''))],capture_output=True,text=True,timeout=30)
 assert build.returncode==0,build.stderr
 run=subprocess.run([str(p.with_suffix(''))],capture_output=True,text=True,timeout=30)
 results.append({'variant':name,'exit_code':run.returncode,'stdout':run.stdout,'stderr':run.stderr,'compiler_stderr':build.stderr})
print(json.dumps(results,indent=2));(r/'serialized-results.json').write_text(json.dumps(results,indent=2)+'\n')

expected = [(0, 'TOTAL=15 FAILED=0'), (1, 'TOTAL=15 FAILED=1'), (0, 'TOTAL=15 FAILED=0')]
if extra: expected.append((0, 'TOTAL=15 FAILED=0'))
passed = all(result['exit_code'] == code
             and result['stdout'].splitlines()[-1:] == [last_line]
             and not result['stderr'] and not result['compiler_stderr']
             for result, (code, last_line) in zip(results, expected))
raise SystemExit(0 if passed else 1)
